#  2. 기존 실무 가이드 완벽 복원: 레인보우TV/CMB 브랜드 보이스, 4050~6070 톤, 직접 호명 금지
#  3. 스마트 심리학 반영: 활성/이탈위험 등 세그먼트에 따른 톤앤매너 자동 조절
