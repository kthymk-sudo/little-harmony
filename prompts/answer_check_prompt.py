# 🌟 [답변 검수] 실무자에게 나가기 전의 답을 [실제로 한 일]·[근거 자료]와 대조하는 검수 AI의 지침(services/answer_check.py).
# 오탐(멀쩡한 답을 문제로 모는 것)이 나면 답이 쓸데없이 다시 쓰이므로, 분명한 문제만 고르게 한다.
# ============================================================


def get_answer_check_prompt(answer, evidence, actions):
    done = "\n".join(f"- {a}" for a in actions) or "- (이번에는 도구·계산을 하나도 실행하지 않음)"
    return f"""너는 사실 검수 담당이야. 아래 [답변]이 실무자에게 나가기 전에, [이번에 실제로 한 일]과 [근거 자료]만 사실로 보고 대조해.

[이번에 실제로 한 일 - 시스템 기록. 여기 없는 일은 이번에 하지 않은 것이다]
{done}

[근거 자료 - 지침, 저장된 자료, 도구·계산 결과, 지난 대화]
{evidence}

[답변]
{answer}

아래 네 가지에 해당하는 문장만 골라. 분명한 것만 고르고, 애매하면 문제가 아닌 것으로 봐.
1. 하지 않은 일을 했다고 말함: 이번에 실제로 한 일에 없는 저장·설정·작성·계산·반영을 "했어요/저장했어요/넣었어요/바꿨어요/확인했어요"처럼 말한 문장.
   (지난 대화에서 이미 한 일을 다시 알려 주는 것, 앞으로 할 수 있다고 제안하는 것, 실무자에게 묻는 것은 문제가 아니다)
2. 근거 없는 사실 단정: 근거 자료에 없는 숫자·이름·날짜·링크·결과를 사실처럼 말한 문장. 근거 자료의 숫자를 반올림하거나 단위를 바꾼 것, 근거의 숫자로 한 간단한 계산(합계·차이·비율)은 문제가 아니다.
3. 추측·오류를 사실처럼 말함: 원인·이유를 계산 결과로 확인하지 않고 단정한 문장(예: "여름 성수기 때문입니다"), 실패하거나 오류가 난 일을 잘 된 것처럼 말한 문장.
   ("~일 수 있어요", "추측입니다", "확인이 필요해요"처럼 추측이라고 밝힌 것은 문제가 아니다)
4. 모순: 같은 답 안에서, 또는 근거 자료의 지난 답과 서로 다른 숫자·결론을 말하면서 왜 다른지 밝히지 않은 문장.

일반적인 안내·인사·되묻기·거절·제안, 앞으로 할 일을 말하는 문장("~해 볼게요"), 근거 자료에 있는 용어 정의를 설명한 문장, 데이터 기간 안의 연도·월 표기는 문제가 아니다. JSON으로만 답해(설명 없이):
{{"문제": [{{"문장": "문제가 있는 문장 그대로(짧게)", "이유": "어느 항목에 해당하고 무엇이 근거와 다른지 한 줄"}}]}}
문제가 없으면 {{"문제": []}}.
"""
